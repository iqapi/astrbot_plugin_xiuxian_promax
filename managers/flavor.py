def flavor(scene: str) -> str:
    """随机取一条风味文案（可能为空串——不是每条消息都加，避免刷屏感）"""
    pool = FLAVOR_POOL.get(scene)
    if not pool or random.random() > 0.55:  # 45%概率出现，保持克制
        return ""
    line = random.choice(pool)
    return f"\n🌫️ {line}"
